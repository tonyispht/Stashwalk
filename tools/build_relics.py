# -*- coding: utf-8 -*-
"""Generates relics.js. Recipes are written against base-item NAMES and resolved to the
indices items.js actually uses, so a reordering of items.js can never silently misalign them."""
import re, json, sys

src = open('items.js', encoding='utf-8').read()
block = src[src.index('const BASES = ['):src.index('];', src.index('const BASES = ['))]
BASES = re.findall(r"\['([^']+)','([^']+)'\]", block)
NAME_TO_IDX = {n: i for i, (e, n) in enumerate(BASES)}
print(f"{len(BASES)} base items found")

# tier -> (workshop level required, display rarity, minimum rarity of each ingredient)
TIER = {1: (1, 2, 0), 2: (2, 2, 1), 3: (3, 3, 2), 4: (4, 3, 2), 5: (5, 4, 3)}

RELICS = [
 (1,'🎖️','Trailblazer’s Badge',['Compass','Trail Map','Hiking Boot'],'Earned by everyone who kept walking when the path got dull.'),
 (1,'🪔','Hearthflame Lamp',['Candle','Flashlight','Old Key'],'Burns with the light of every camp you ever made.'),
 (1,'🧺','Forager’s Basket',['Mushroom','Acorn','Herb Sprig'],'Heavier than it looks, and always a little damp.'),
 (1,'🪝','Hook of Still Water',['Fishing Rod','Wave','Trout'],'Cast it and the water forgets to ripple.'),
 (2,'🧿','Nightwatcher’s Eye',['Telescope','Star','Owl'],'It blinks only when you are not looking at it.'),
 (2,'💮','Bloomwoven Circlet',['Blossom','Tulip','Sunflower','Clover'],'Woven at dawn; it has not wilted since.'),
 (2,'🪘','Thunder Drum',['Drum','Lightning Bolt','Cloud Wisp'],'Strike it once and somewhere far off it rains.'),
 (2,'🫙','Amber Hive',['Bee','Honey Pot','Amphora'],'A whole summer, sealed and still humming.'),
 (3,'🪬','Warden’s Ward',['Shield','Crossed Blades','Bone'],'Carried by those who guard the quiet places.'),
 (3,'⚗️','Elixir of Deep Woods',['Potion','Mushroom','Herb Sprig','Dewdrop'],'Tastes of moss, rain and something older.'),
 (3,'🗿','Stone Sentinel',['Pickaxe','Gemstone','Bone'],'It has watched this valley longer than the trees.'),
 (3,'🪶','Skyfeather Mantle',['Eagle','Cloud Wisp','Scarf'],'Worn on the shoulders, it makes the wind polite.'),
 (4,'🌋','Dragonfire Heart',['Dragon','Ember','Gemstone','Crown'],'Still warm. It will always be still warm.'),
 (4,'✴️','Unicorn’s Prism',['Unicorn','Rainbow Shard','Crystal Ball'],'Splits one wish into seven smaller ones.'),
 (4,'⏳','Hourglass of Still Hours',['Pocket Watch','Scroll','Dewdrop'],'The sand falls upward on the longest day of the year.'),
 (4,'🏔️','Summit Standard',['Hiking Boot','Compass','Trophy'],'Planted on a peak nobody else bothered to climb.'),
 (5,'💠','Heart of the Wild',['Fox','Bear','Owl','Deer'],'Four creatures agreed, once, to share a single heartbeat.'),
 (5,'🌌','Cosmos in a Jar',['Star','Crescent Moon','Sunstone','Amphora'],'Hold it to your ear and you can hear the dark.'),
 (5,'🎆','Everlight',['Flashlight','Candle','Lantern','Sunstone'],'No night has ever outlasted it.'),
 (5,'🪞','Mirror of Many Trails',['Trail Map','Compass','Telescope','Crystal Ball'],'Shows every path you did not take. Kindly.'),
]

out, missing = [], []
for i, (tier, emoji, name, ings, flavor) in enumerate(RELICS):
    lvl, rar, minr = TIER[tier]
    req = []
    for ing in ings:
        if ing not in NAME_TO_IDX: missing.append(ing); continue
        req.append([NAME_TO_IDX[ing], minr])
    out.append({'id': 'c%d' % i, 'e': emoji, 'n': name, 'r': rar, 'tier': tier, 'lvl': lvl,
                'req': req, 'flavor': flavor})
if missing:
    sys.exit('ingredient names not found in items.js: %s' % sorted(set(missing)))

js = """// Crafted-only items ("relics"). These never appear in chests - the only way to get one is to
// build it in the Workshop, or trade with a player who did. Generated by tools/build_relics.py.
(function () {
  const RELICS = %s;
  // Relics join the item tables so they show on the Shelf, but NOT ITEMS_BY_R, which is what
  // chests roll from - that is what keeps them craft-only.
  RELICS.forEach(r => { r.base = -1; r.h = 0; r.crafted = true; window.ITEMS.push(r); window.ITEM_BY_ID[r.id] = r; });
  window.RELICS = RELICS;
})();
""" % json.dumps(out, ensure_ascii=False, separators=(',', ':'))
open('relics.js', 'w', encoding='utf-8').write(js)
print('wrote relics.js:', len(out), 'relics')
for t in range(1, 6):
    names = [r['n'] for r in out if r['tier'] == t]
    print(f"  tier {t} (workshop level {TIER[t][0]}): {', '.join(names)}")
